/* On the Oct 1, 2026 card the Service column equals the utility list rate in every market. */
export const MARKETS: Market[] = RAW.map((m) => ({ ...m, service: m.utility }));

/** Billable service messages after the free monthly tier (1,000 × business phone numbers). */
export function serviceBreakdown(m: Market, volume: number, numbers = 1) {
  const allowance = FREE_SERVICE_PER_NUMBER * Math.max(1, numbers);
  const free = Math.min(volume, allowance);
  const billable = Math.max(0, volume - allowance);
  return { allowance, free, billable, rate: m.service, cost: billable * m.service, freeValue: free * m.service };
}

/* ---------------- helpers ---------------- */

export function listRate(m: Market, t: MsgType): number | null {
  switch (t) {
    case "marketing":
      return m.marketing;
    case "utility":
      return m.utility;
    case "authentication":
      return m.authentication;
    case "authIntl":
      return m.authIntl;
    case "service":
      return m.service; // charged from the 1,001st message per number per month
  }
}

export function tiersFor(m: Market, t: MsgType): TierRow[] | null {
  switch (t) {
    case "marketing":
      return null; // flat rate — no volume tiers
    case "utility":
      return m.u;
    case "authentication":
      return m.a;
    case "authIntl":
      return m.ai;
    case "service":
      return null; // flat rate — service messages have no volume tiers
  }
}

export function tierForVolume(m: Market, t: MsgType, volume: number): TierRow | null {
  const ts = tiersFor(m, t);
  if (!ts) return null;
  return ts.find((r) => volume >= r.from && (r.to === null || volume <= r.to)) ?? ts[ts.length - 1];
}

export function tierIndex(m: Market, t: MsgType, volume: number): number {
  const ts = tiersFor(m, t);
  if (!ts) return -1;
  return ts.findIndex((r) => volume >= r.from && (r.to === null || volume <= r.to));
}

export function discountPct(m: Market, t: MsgType, rate: number): number {
  const l = listRate(m, t);
  if (l === null || l === 0) return 0;
  return Math.round((1 - rate / l) * 1000) / 10;
}

export function topTier(m: Market, t: MsgType): TierRow | null {
  const ts = tiersFor(m, t);
  return ts ? ts[ts.length - 1] : null;
}

export const fmtINR = (n: number, d = 4) =>
  "₹" + n.toLocaleString("en-IN", { minimumFractionDigits: d, maximumFractionDigits: d });

export const fmtNum = (n: number) => n.toLocaleString("en-IN");

export function tierRangeLabel(r: TierRow): string {
  if (r.to === null) return `${fmtNum(r.from)}+`;
  return `${fmtNum(r.from)} – ${fmtNum(r.to)}`;
}

